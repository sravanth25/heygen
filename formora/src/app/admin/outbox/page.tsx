import Link from "next/link";
import { requireAdmin } from "@/lib/server/admin-auth";
import { read } from "@/lib/server/db";

export const metadata = { title: "Email outbox" };
export const dynamic = "force-dynamic";

export default async function OutboxPage() {
  await requireAdmin();
  const [emails, orders] = await read((db) => [db.outbox, db.orders] as const);
  return (
    <>
      <h1 className="text-3xl">Email outbox</h1>
      <p className="mt-2 mb-6 max-w-2xl rounded-lg bg-notice p-3 text-sm">
        No email provider is connected. Messages below were generated by the store but <strong>not delivered</strong>. Connect a
        transactional email provider before launch.
      </p>
      {emails.length === 0 && <p className="text-muted">No emails yet.</p>}
      <ul className="space-y-4">
        {emails.map((e) => {
          const order = orders.find((o) => o.id === e.orderId);
          return (
            <li key={e.id} className="card p-5">
              <div className="flex flex-wrap items-center justify-between gap-2 text-sm">
                <span className="font-semibold">{e.subject}</span>
                <span className="text-muted">{new Date(e.createdAt).toLocaleString("en-US")}</span>
              </div>
              <p className="mt-1 text-sm text-muted">
                To {e.to} · {e.kind.replaceAll("_", " ")} · not sent
                {order && (
                  <>
                    {" "}
                    ·{" "}
                    <Link href={`/admin/orders/${order.id}`} className="link">
                      {order.number}
                    </Link>
                  </>
                )}
              </p>
              <pre className="mt-3 overflow-x-auto rounded-lg bg-warm p-3 font-sans text-sm whitespace-pre-wrap">{e.body}</pre>
            </li>
          );
        })}
      </ul>
    </>
  );
}
